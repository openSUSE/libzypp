"""Shared helpers for the maintainer-docs tools (headings, GitHub anchors, links)."""
import re
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent
TOC_BEGIN = "<!-- TOC (generated by tools/toc.py, do not edit) -->"
TOC_END = "<!-- /TOC -->"

_LINK = re.compile(r"\[([^\]]*)\]\(([^)]*)\)")


_FENCE_OPEN = re.compile(r"^\s*(`{3,}|~{3,})(.*)$")


def strip_code(lines):
    """Yield (lineno, line) for lines outside fenced code blocks.

    CommonMark rules: a fence opens with 3+ backticks or tildes (a backtick
    fence's info string must not contain backticks) and is closed only by the
    same character, repeated at least as often, followed by nothing but
    whitespace.
    """
    fence = None  # (char, length) of the open fence
    for no, line in enumerate(lines, 1):
        m = _FENCE_OPEN.match(line)
        if fence is None:
            if m and not (m.group(1)[0] == "`" and "`" in m.group(2)):
                fence = (m.group(1)[0], len(m.group(1)))
                continue
            yield no, line
        else:
            ch, n = fence
            if m and m.group(1)[0] == ch and len(m.group(1)) >= n and not m.group(2).strip():
                fence = None


def heading_text(raw):
    """Plain text of a heading: links reduced to their text."""
    return _LINK.sub(r"\1", raw).strip()


def slugify(text):
    """GitHub-style anchor for a heading text (without duplicate suffix)."""
    t = heading_text(text).lower()
    t = re.sub(r"[^\w\- ]", "", t)  # keeps unicode letters/digits, '_', '-', ' '
    return t.replace(" ", "-")


def headings(path, lines=None):
    """List of (level, text, anchor) for all headings, GitHub duplicate rules applied.

    Pass `lines` to use them instead of reading `path`.
    """
    seen = {}
    out = []
    if lines is None:
        lines = Path(path).read_text(encoding="utf-8").splitlines()
    for _, line in strip_code(lines):
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        base = slugify(m.group(2))
        # github-slugger: on a clash, count up the base's suffix until the anchor is unused
        anchor = base
        while anchor in seen:
            seen[base] += 1
            anchor = f"{base}-{seen[base]}"
        seen[anchor] = 0
        out.append((len(m.group(1)), heading_text(m.group(2)), anchor))
    return out


def explicit_anchors(path):
    text = Path(path).read_text(encoding="utf-8")
    return set(re.findall(r'<a\s+(?:id|name)="([^"]+)"', text))


# A code span opens and closes with backtick runs of equal length.
_CODE_SPAN = re.compile(r"(?<!`)(`+)(?!`).*?(?<!`)\1(?!`)")


def links(path):
    """Yield (lineno, text, target) for markdown links outside code blocks/inline code."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    for no, line in strip_code(lines):
        line = _CODE_SPAN.sub("", line)
        for m in _LINK.finditer(line):
            yield no, m.group(1), m.group(2).strip()
